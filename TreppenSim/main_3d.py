"""
TreppenSchlepper — 3-D simulation entry point.

Runs the full step cycle (2-D physics + 3-D lateral analysis) and saves:
  results/phases_3d.png        — 3-D isometric drawing of all 4 phases
  results/sim_3d_lateral.png   — lateral stability: margin vs payload offset
                                  and margin vs approach skew angle

Usage:
    uv run python main_3d.py
"""

import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt   # noqa: E402
import numpy as np                # noqa: E402

from sim.params_3d import SimParams3D, Geometry3DParams  # noqa: E402
from sim.sim_3d import run_step_cycle_3d                  # noqa: E402

os.makedirs("results", exist_ok=True)


# ── Run 3-D simulation ────────────────────────────────────────────────────────

p3d = SimParams3D()
result = run_step_cycle_3d(p3d)

print()
print(result.cycle_2d.summary())
print()
print(result.lateral.summary())
print()


# ── Figure 1 — 3-D phase drawing (generated by draw_3d.py) ───────────────────

import draw_3d  # noqa: E402, F401  (side-effect: saves phases_3d.png)


# ── Figure 2 — Lateral stability analysis ────────────────────────────────────

G = 9.81
lat = result.lateral
geo3d = p3d.geo3d
m = p3d.base.mass

fig, (ax_off, ax_skew) = plt.subplots(1, 2, figsize=(12, 5))
fig.suptitle(
    "TreppenSchlepper — Phase 3 Lateral Stability (3-D)\n"
    f"Wheel track = {geo3d.wheel_track * 100:.0f} cm  |  "
    f"OS width = {geo3d.W_os * 100:.0f} cm  |  "
    f"Payload = {m.m_payload:.0f} kg",
    fontsize=12, fontweight="bold",
)


# ── Panel A — Lateral stability margin vs payload offset ──────────────────────

offsets = np.linspace(0, geo3d.wheel_track / 2 * 1.1, 200)   # m
m_total = m.m_phase3_os + m.m_phase4
com_y   = m.m_payload * offsets / m_total                     # CoM_y of whole device
margin  = lat.track_half - com_y                               # m

ax_off.plot(offsets * 100, margin * 100, color="#9467bd", lw=2)
ax_off.axhline(0, color="red", lw=1.5, ls="--", label="Tip-over")
ax_off.axvline(lat.max_payload_offset * 100, color="goldenrod",
               lw=1.5, ls="--",
               label=f"Max safe offset ({lat.max_payload_offset*100:.0f} cm)")
ax_off.fill_between(offsets * 100, margin * 100, 0,
                    where=margin >= 0, alpha=0.15, color="#9467bd",
                    label="Stable")
ax_off.fill_between(offsets * 100, margin * 100, 0,
                    where=margin < 0,  alpha=0.25, color="red",
                    label="Tipping")
ax_off.set_xlabel("Payload lateral offset from centreline (cm)", fontsize=9)
ax_off.set_ylabel("Lateral stability margin (cm)", fontsize=9)
ax_off.set_title("Lateral Margin vs Payload Offset", fontsize=10, fontweight="bold")
ax_off.legend(fontsize=8)
ax_off.grid(True, alpha=0.3)
ax_off.tick_params(labelsize=8)
ax_off.text(
    lat.max_payload_offset * 100 * 0.5,
    margin.max() * 100 * 0.5,
    f"Tip-over at\n±{lat.max_payload_offset*100:.0f} cm offset",
    ha="center", va="center", fontsize=8, color="#9467bd",
    bbox=dict(boxstyle="round,pad=0.3", fc="white", ec="#9467bd", alpha=0.8),
)


# ── Panel B — Lateral margin vs approach skew angle ───────────────────────────

# When device is skewed by θ, left and right front wheels reach the step edge
# at different times.  Effective x-overhang difference = track_half * sin(θ).
# We compute the longitudinal stability margin that remains on the lagging side.
skew_deg = np.linspace(0, 35, 200)
skew_rad = np.radians(skew_deg)

long_margin_cm = result.cycle_2d.phase3.min_stability_margin * 100  # cm
track_half_cm  = lat.track_half * 100                                # cm

# Lagging wheel contacts later by track_half * sin(θ) in x.
# Remaining longitudinal stability margin on that side:
remaining_long = long_margin_cm - track_half_cm * np.sin(skew_rad)

ax_skew.plot(skew_deg, remaining_long, color="#1f77b4", lw=2,
             label="Remaining longitudinal margin (lagging side)")
ax_skew.axhline(0, color="red", lw=1.5, ls="--", label="Tip-over threshold")
ax_skew.axvline(lat.max_safe_skew_deg, color="goldenrod", lw=1.5, ls="--",
                label=f"Max safe skew ({lat.max_safe_skew_deg:.0f}°)")
ax_skew.fill_between(skew_deg, remaining_long, 0,
                     where=remaining_long >= 0, alpha=0.15, color="#1f77b4",
                     label="Stable")
ax_skew.fill_between(skew_deg, remaining_long, 0,
                     where=remaining_long <  0, alpha=0.25, color="red",
                     label="Tipping risk")
ax_skew.set_xlabel("Approach skew angle (°)", fontsize=9)
ax_skew.set_ylabel("Longitudinal stability margin — lagging side (cm)", fontsize=9)
ax_skew.set_title("Stability vs Approach Skew Angle", fontsize=10, fontweight="bold")
ax_skew.legend(fontsize=8)
ax_skew.grid(True, alpha=0.3)
ax_skew.tick_params(labelsize=8)

plt.tight_layout(rect=[0, 0, 1, 0.92])
out2 = os.path.join("results", "sim_3d_lateral.png")
fig.savefig(out2, dpi=150, bbox_inches="tight")
plt.close(fig)
print(f"Lateral stability plot saved -> {out2}")
